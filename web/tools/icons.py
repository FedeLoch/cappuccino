"""Turns the Android vector icons in app/src/main/res/drawable into an ES module of SVG strings,
so the web version draws the very same icons without keeping copies of them."""

import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ANDROID = "{http://schemas.android.com/apk/res/android}"
ATTRIBUTES = {
    "pathData": "d",
    "fillColor": "fill",
    "strokeColor": "stroke",
    "strokeWidth": "stroke-width",
    "strokeLineCap": "stroke-linecap",
    "strokeLineJoin": "stroke-linejoin",
}


def convert(path):
    root = ET.parse(path).getroot()
    if root.tag != "vector":
        return None
    width = root.get(ANDROID + "viewportWidth")
    height = root.get(ANDROID + "viewportHeight")
    parts = []

    def walk(node):
        for child in node:
            if child.tag == "group":
                transform = []
                tx, ty = child.get(ANDROID + "translateX"), child.get(ANDROID + "translateY")
                sx, sy = child.get(ANDROID + "scaleX"), child.get(ANDROID + "scaleY")
                if tx or ty:
                    transform.append(f"translate({tx or 0} {ty or 0})")
                if sx or sy:
                    transform.append(f"scale({sx or 1} {sy or 1})")
                parts.append(f'<g transform="{" ".join(transform)}">')
                walk(child)
                parts.append("</g>")
            elif child.tag == "path":
                attributes = {"fill": "none"}
                for name, svg in ATTRIBUTES.items():
                    value = child.get(ANDROID + name)
                    if value is not None:
                        attributes[svg] = value
                parts.append("<path " + " ".join(f'{k}="{v}"' for k, v in attributes.items()) + "/>")

    walk(root)
    return f'<svg viewBox="0 0 {width} {height}" aria-hidden="true">{"".join(parts)}</svg>'


def main():
    source, target = Path(sys.argv[1]), Path(sys.argv[2])
    icons = {}
    for file in sorted(source.glob("ic_*.xml")):
        svg = convert(file)
        if svg:
            icons[file.stem[3:]] = svg
    target.write_text(
        "// Generated by web/tools/icons.py from app/src/main/res/drawable. Don't edit.\n"
        f"export default {json.dumps(icons, indent=1)};\n"
    )


if __name__ == "__main__":
    main()
