package art.cappuccino.paint

/** The app's languages. To add one, add its table below and an entry here. */
enum class Language(val code: String, val label: String) {
    ENGLISH("en", "English"),
    SPANISH("es", "Español"),
}

object I18n {
    var language = Language.ENGLISH

    /** Picks the saved language, or follows the device when there isn't one. */
    fun choose(saved: String?, deviceLanguage: String) {
        val code = saved ?: deviceLanguage
        language = Language.entries.firstOrNull { it.code == code } ?: Language.ENGLISH
    }
}

/**
 * Translates English source text. Numbered marks such as %1 are replaced by [values], and text
 * without a translation, like an artist's own names, stays as it is.
 */
fun tr(text: String, vararg values: Any): String {
    var result = if (I18n.language == Language.SPANISH) SPANISH[text] ?: text else text
    values.forEachIndexed { index, value -> result = result.replace("%${index + 1}", value.toString()) }
    return result
}

